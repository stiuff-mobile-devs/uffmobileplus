/// URLs dos guias online abertos pelo botão de ajuda (?) das AppBars
/// (`AppBars.helpAction`).
///
/// Enquanto a URL de uma tela for `null`, o botão mostra um aviso de que o
/// manual de guias está sendo preparado. Para ativar, cole a URL aqui, ex.:
/// `static const String? servicos = 'https://...';`
class HelpGuides {
  HelpGuides._();

  /// Tela "Serviços" (lista de módulos).
  static const String? servicos = null;

  /// Tela "Configurações".
  static const String? configuracoes = null;

  /// Tela "Sobre".
  static const String? sobre = null;
}
